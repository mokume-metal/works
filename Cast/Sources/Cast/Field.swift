import Foundation
import simd

/// 自由変数の唯一の置き場。
///
/// **数はここにしか無い。** 彫り出しも、測る側も、絵も、全部ここを読む — 割れると
/// 「彫った形」と「測った被覆」が食い違い、どちらが正しいのか分からなくなる。
///
/// ## 長さの基準は円の半径
///
/// 3 つの狙い (円・正三角形・正方形) は**面積をそろえて**あるので、寸法は円の半径
/// `unit` ひとつで決まる。世界の単位は画素と同じ縮尺で取ってある (1920 × 1080 の面に
/// 対して半径 260 — 直径が面の短辺のおよそ半分)。
///
/// ## 効くのは `shear` ひとつ
///
/// 床へ落ちる影は「高さに比例した平行移動」でしかない (``Shear``)。高さ `h` の塊が
/// 作る**ずれの総量 `T = κ·h`** が、3 つの姿勢で別々の形を作れる余地そのものになる —
/// `T = 0` (真上からの光) だと 3 つの影は完全に同じになり、円と三角と四角を作り分ける
/// ことが**原理的にできない**。
///
/// 仰角 `elevation` は絵のため (影の伸びと床の明るさ) に決め、`shear` で余地を取る。
/// どちらを動かしても `h = T / κ` が動くだけである。
enum Field {
    /// 円の半径。**作品の長さはすべてこれの倍数**である。
    static let unit: Float = 260

    /// 光の仰角 (度)。**寝かせるほど影は長く伸び、床は暗くなる。**
    static let elevation: Float = 45

    /// ずれの総量 `T` を `unit` で測ったもの。**被覆率を決める主役。**
    ///
    /// 1.2 から 2.2 まで掃いて、3 つの狙いの最小被覆はどれも 94–95% で頭打ちだった
    /// (`min` が最大になったのは 1.8)。ここを下げると三角形の角から欠ける。
    static let shear: Float = 1.8

    /// 正三角形の向き (度)。0 は「角が光の進む向き」。5 度刻みで掃いて決めた。
    static let triangleAngle: Float = 35
    /// 正方形の向き (度)。
    static let squareAngle: Float = 0

    /// 水平の刻み。**被覆率にはほとんど効かず、効くのは縁の階段と面の枚数**である。
    static let grid = 192

    /// 塊の下端の高さ。
    ///
    /// **高さがそのまま「塊と影の離れ具合」になる。** 影の中心は `κ·(中心の高さ)` だけ
    /// 横へずれるので、低く浮かべると画面の上で塊が自分の影に重なって、影の形が読めなく
    /// なる。彫り出しは中心からの高さしか見ないので、ここを動かしても塊の形は変わらない。
    static let clearance: Float = 520

    // MARK: - 導かれるもの

    /// `cot(仰角)` — 高さ 1 あたり、影が横へずれる量。
    static var kappa: Float { 1 / tan(elevation * .pi / 180) }
    /// ずれの総量 `T`。
    static var shearLength: Float { shear * unit }
    /// 塊の高さ `h = T / κ`。
    static var height: Float { shearLength / kappa }
    /// 塊の水平の広がり (片側)。
    ///
    /// **当て推量ではなく円の制約から出る。** 残るセルは必ず円の影の内側にあり、
    /// 高さのずれは最大でも `T/2` なので `|(x, z)| ≤ r + T/2`。
    static var extent: Float { unit + shearLength / 2 }
    /// 塊の中心の高さ。
    static var centerHeight: Float { clearance + height / 2 }
    /// 塊の縦軸が床のどこに立っているか。
    ///
    /// **3 つの影が床の原点で重なるように決める** — 中心の影が原点へ落ちる位置である。
    static var axis: SIMD2<Float> { -kappa * centerHeight * Shear.heading }

    /// 床の広さ (一辺)。**画面の外まで敷く** — 端が見えると床が板に見える。
    static let floorSpan: Float = 12000
}
